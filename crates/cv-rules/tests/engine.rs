#[test]
fn sources_md_is_generated_from_citations() {
    let rules = Ruleset::v1();
    // Normalize CRLF so a Windows checkout with autocrlf still compares.
    let on_disk = include_str!("../../../rulepacks/SOURCES.md").replace("\r\n", "\n");
    assert_eq!(
        on_disk,
        rules.sources_markdown().as_str(),
        "rulepacks/SOURCES.md is stale: cargo run -p cv-rules --example gen-sources > rulepacks/SOURCES.md"
    );
    for p in rules.packs() {
        for r in &p.rules {
            assert!(on_disk.contains(&format!("`{}`", r.id)));
            assert!(on_disk.contains(&r.citation.url));
            assert!(on_disk.contains(&r.citation.frozen_quote));
        }
    }
}

#[test]
fn uncited_rules_do_not_load() {
    let pack = |citation: &str| {
        format!(
            r#"
[pack]
id = "p"
version = 1
description = "d"
[[rule]]
id = "R"
severity = "Info"
tier = "Heuristic"
archetypes = ["Any"]
remediation = "r"
check = {{ Exists = {{ artifact = "Html", selector = {{ Html = "title" }} }} }}
{citation}
"#
        )
    };
    assert!(RulePack::from_toml(&pack("")).is_err());
    let cite = |url: &str, quote: &str, cap: &str| {
        format!(
            "[rule.citation]\nsource = \"s\"\nurl = \"{url}\"\nfrozen_quote = \"{quote}\"\ncaptured = \"{cap}\""
        )
    };
    assert!(RulePack::from_toml(&pack(&cite("https://x.example/", "q", "2026-11-23"))).is_ok());
    assert!(RulePack::from_toml(&pack(&cite("http://x.example/", "q", "2026-11-23"))).is_err());
    assert!(RulePack::from_toml(&pack(&cite("https://x.example/", " ", "2026-11-23"))).is_err());
    assert!(RulePack::from_toml(&pack(&cite("https://x.example/", "q", "Nov 2026"))).is_err());
    let bad_sel =
        pack(&cite("https://x.example/", "q", "2026-11-23")).replace("\"title\"", "\"a:hover\"");
    assert!(RulePack::from_toml(&bad_sel).is_err());
}

