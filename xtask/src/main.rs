//! xtask — repo automation. Subcommands:
//! - `codegen [--check]` — regenerate the module registry
//!   (`crates/cv-model/src/modules/mod.rs`) from `modules/<lane>/` dirs.
//! - `png-diff <a.png> <b.png> [--tolerance N] [--max-ratio R]` — the
//!   canonical-rasterizer PNG golden comparison.
//! - `parity` — draft-sketch ↔ Boris parity report.
//! - `fetch-boris [--src <checkout>]` — build the pinned boris (zig
//!   0.17.x, network) and stage it at `vendor/engines/boris`.
//! - `release [--out <dir>]` — version-stamped package with the staged
//!   boris bundled (see `release.rs`).
//!
//! Planned: `fixtures refresh`.

mod release;

use std::path::{Path, PathBuf};
use std::process::ExitCode;

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("xtask lives in the workspace root")
        .to_path_buf()
}

fn modules_dir() -> PathBuf {
    root().join("crates/cv-model/src/modules")
}

/// Lane module dirs: `modules/<name>/mod.rs`, sorted for determinism.
fn lanes(dir: &Path) -> Vec<String> {
    let mut out: Vec<String> = std::fs::read_dir(dir)
        .map(|rd| {
            rd.filter_map(|e| e.ok())
                .filter(|e| e.path().join("mod.rs").is_file())
                .filter_map(|e| e.file_name().to_str().map(str::to_string))
                .filter(|n| n.chars().all(|c| c.is_ascii_lowercase() || c == '_'))
                .collect()
        })
        .unwrap_or_default();
    out.sort();
    out
}

fn render_registry(lanes: &[String]) -> String {
    let mut s = String::from(
        "// @generated by `cargo run -p xtask -- codegen` — DO NOT EDIT.\n\
         // Lanes add `modules/<lane>/mod.rs` exposing `pub fn register(&mut Registry)`\n\
         // and rerun codegen; `scripts/check-module-registry.sh` gates drift.\n\n",
    );
    for l in lanes {
        s.push_str(&format!("pub mod {l};\n"));
    }
    s.push_str("\npub fn register_all(r: &mut crate::module::Registry) {\n");
    for l in lanes {
        s.push_str(&format!("    {l}::register(r);\n"));
    }
    s.push_str("}\n");
    s
}

fn codegen(check: bool) -> ExitCode {
    let dir = modules_dir();
    let want = render_registry(&lanes(&dir));
    let path = dir.join("mod.rs");
    let have = std::fs::read_to_string(&path).unwrap_or_default();
    if have.replace("\r\n", "\n") == want {
        println!("module registry up to date ({})", path.display());
        return ExitCode::SUCCESS;
    }
    if check {
        eprintln!(
            "module registry is stale: run `cargo run -p xtask -- codegen`\n--- want ---\n{want}"
        );
        return ExitCode::FAILURE;
    }
    if let Err(e) = std::fs::write(&path, want) {
        eprintln!("write {}: {e}", path.display());
        return ExitCode::FAILURE;
    }
    println!("wrote {}", path.display());
    ExitCode::SUCCESS
}

fn read_rgba(p: &str) -> Result<(u32, u32, Vec<u8>), String> {
    let f = std::fs::File::open(p).map_err(|e| format!("{p}: {e}"))?;
    let mut dec = png::Decoder::new(std::io::BufReader::new(f));
    dec.set_transformations(png::Transformations::EXPAND | png::Transformations::STRIP_16);
    let mut r = dec.read_info().map_err(|e| format!("{p}: {e}"))?;
    let mut buf = vec![0; r.output_buffer_size().ok_or("png too large")?];
    let info = r.next_frame(&mut buf).map_err(|e| format!("{p}: {e}"))?;
    buf.truncate(info.buffer_size());
    let ch = match info.color_type {
        png::ColorType::Rgba => 4,
        png::ColorType::Rgb => 3,
        png::ColorType::GrayscaleAlpha => 2,
        _ => 1,
    };
    let rgba = buf
        .chunks(ch)
        .flat_map(|c| match ch {
            4 => [c[0], c[1], c[2], c[3]],
            3 => [c[0], c[1], c[2], 255],
            2 => [c[0], c[0], c[0], c[1]],
            _ => [c[0], c[0], c[0], 255],
        })
        .collect();
    Ok((info.width, info.height, rgba))
}

/// Fraction of pixels whose max channel delta exceeds `tolerance`.
fn diff_ratio(a: &[u8], b: &[u8], tolerance: u8) -> f64 {
    let px = a.len() / 4;
    let bad = a
        .chunks(4)
        .zip(b.chunks(4))
        .filter(|(x, y)| {
            x.iter()
                .zip(y.iter())
                .any(|(p, q)| p.abs_diff(*q) > tolerance)
        })
        .count();
    bad as f64 / px.max(1) as f64
}

fn png_diff(args: &[String]) -> ExitCode {
    let (Some(a), Some(b)) = (args.first(), args.get(1)) else {
        eprintln!("usage: xtask png-diff <a.png> <b.png> [--tolerance N] [--max-ratio R]");
        return ExitCode::FAILURE;
    };
    let opt = |name: &str, d: f64| {
        args.iter()
            .position(|x| x == name)
            .and_then(|i| args.get(i + 1))
            .and_then(|v| v.parse().ok())
            .unwrap_or(d)
    };
    let tol = opt("--tolerance", 2.0) as u8;
    let max = opt("--max-ratio", 0.0);
    let (ia, ib) = match (read_rgba(a), read_rgba(b)) {
        (Ok(x), Ok(y)) => (x, y),
        (Err(e), _) | (_, Err(e)) => {
            eprintln!("{e}");
            return ExitCode::FAILURE;
        }
    };
    if (ia.0, ia.1) != (ib.0, ib.1) {
        eprintln!("size mismatch: {}x{} vs {}x{}", ia.0, ia.1, ib.0, ib.1);
        return ExitCode::FAILURE;
    }
    let r = diff_ratio(&ia.2, &ib.2, tol);
    println!(
        "{a} vs {b}: {:.4}% pixels differ (tolerance {tol})",
        r * 100.0
    );
    if r > max {
        ExitCode::FAILURE
    } else {
        ExitCode::SUCCESS
    }
}

/// Draft-sketch ↔ Boris parity report (see `crates/cv-widgets/tests/parity.rs`).
fn parity() -> ExitCode {
    let cargo = std::env::var("CARGO").unwrap_or_else(|_| "cargo".into());
    let status = std::process::Command::new(cargo)
        .args([
            "test",
            "-p",
            "cv-widgets",
            "--test",
            "parity",
            "--",
            "--nocapture",
        ])
        .status();
    match status {
        Ok(s) if s.success() => ExitCode::SUCCESS,
        Ok(_) => ExitCode::FAILURE,
        Err(e) => {
            eprintln!("parity: {e}");
            ExitCode::FAILURE
        }
    }
}

fn report<T>(r: Result<T, String>) -> ExitCode {
    match r {
        Ok(_) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("error: {e}");
            ExitCode::FAILURE
        }
    }
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args.first().map(String::as_str) {
        Some("codegen") => codegen(args.iter().any(|a| a == "--check")),
        Some("png-diff") => png_diff(&args[1..]),
        Some("parity") => parity(),
        Some("fetch-boris") => report(release::fetch_boris(&root(), &args[1..])),
        Some("release") => report(release::release(&root(), &args[1..])),
        _ => {
            eprintln!(
                "usage: xtask <codegen [--check] | png-diff a.png b.png | parity | fetch-boris [--src DIR] | release [--out DIR]>"
            );
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn registry_render_is_sorted_and_checked_in() {
        let want = render_registry(&lanes(&modules_dir()));
        let have = std::fs::read_to_string(modules_dir().join("mod.rs")).unwrap();
        assert_eq!(
            have.replace("\r\n", "\n"),
            want,
            "run `cargo run -p xtask -- codegen`"
        );
    }

    #[test]
    fn render_lists_every_lane() {
        let s = render_registry(&["audit".into(), "demo".into()]);
        assert!(s.contains("pub mod audit;\npub mod demo;"));
        assert!(s.contains("    audit::register(r);\n    demo::register(r);"));
    }

    #[test]
    fn diff_ratio_counts_tolerance() {
        let a = [10, 10, 10, 255, 0, 0, 0, 255];
        let b = [11, 10, 10, 255, 50, 0, 0, 255];
        assert_eq!(diff_ratio(&a, &b, 2), 0.5);
    }
}
